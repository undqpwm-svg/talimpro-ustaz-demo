	function esc(s) {
		return String(s).replace(/[&<>"]/g, function (c) {
			return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
		});
	}

	function top() {
		return '<div class="quiz-top"><span class="q-count">' +
			(step < QUESTIONS.length ? UI[lang].q + ' ' + (step + 1) + ' ' + UI[lang].of + ' ' + QUESTIONS.length : 'Кәсіби бағдар') +
			'</span><div class="lang-switch" role="group" aria-label="Тіл / Язык">' +
			'<button type="button" data-lang="kk"' + (lang === 'kk' ? ' class="on" aria-pressed="true"' : ' aria-pressed="false"') + '>ҚАЗ</button>' +
			'<button type="button" data-lang="ru"' + (lang === 'ru' ? ' class="on" aria-pressed="true"' : ' aria-pressed="false"') + '>РУС</button>' +
			'</div></div>' +
			'<div class="progress"><i style="width:' + Math.round(step / QUESTIONS.length * 100) + '%"></i></div>';
	}

	function results() {
		var score = { R: 0, I: 0, A: 0, S: 0, E: 0, C: 0 };
		picks.forEach(function (t) { score[t]++; });
		return ORDER.slice().sort(function (a, b) {
			return score[b] - score[a] || ORDER.indexOf(a) - ORDER.indexOf(b);
		}).slice(0, 3).map(function (t) {
			return { type: t, pct: Math.round(score[t] / picks.length * 100) };
		});
	}

	function render() {
		var t = UI[lang];
		var html = top();
		if (step < QUESTIONS.length) {
			var q = QUESTIONS[step];
			html += '<h2 class="q-title">' + esc(q[lang]) + '</h2><div class="answers">';
			q.a.forEach(function (a, i) {
				html += '<button type="button" class="answer" data-i="' + i + '">' + esc(lang === 'kk' ? a[1] : a[2]) + '</button>';
			});
			html += '</div>';
			if (step > 0) {
				html += '<button type="button" class="quiz-back">' + t.back + '</button>';
			}
		} else {
			var res = results();
			var lines = [];
			html += '<h2 class="q-title">' + t.resTitle + '</h2><p>' + t.resLead + '</p><div class="result-types">';
			res.forEach(function (r, i) {
				var d = TYPES[r.type][lang];
				lines.push((i + 1) + ') ' + d.name + ' — ' + r.pct + '%');
				html += '<div class="rtype"><h4>' + esc(d.name) + ' <span>' + r.pct + '%</span></h4>' +
					'<div class="bar"><i style="width:' + r.pct + '%"></i></div>' +
					'<p style="margin-top:12px">' + esc(d.text) + '</p>' +
					'<div class="profs"><b>' + t.profs + '</b> ' + esc(d.profs) + '</div></div>';
			});
			html += '</div><p class="note">' + t.note + '</p><div class="btn-row" style="margin-top:20px">' +
				'<a class="btn btn-orange btn-wa" id="quiz-wa" href="#">' + t.wa + '</a>' +
				'<button type="button" class="btn btn-ghost" id="quiz-again">' + t.again + '</button></div>';

			var msg = t.waText + '\n' + lines.join('\n') + '\n' + t.waEnd;
			root.innerHTML = html;
			var link = document.getElementById('quiz-wa');
			var url = talimWaUrl(msg);
			if (url.indexOf('contacts.html') === 0) {
				// Номер WhatsApp ещё не указан — переносим результат в тему формы заявки
				url = 'contacts.html?topic=' + encodeURIComponent('Разбор теста «Кәсіби бағдар»: ' + lines.join('; ')) + '#form';
			} else {
				link.target = '_blank';
				link.rel = 'noopener';
			}
			link.href = url;
			return;
		}
		root.innerHTML = html;
	}

	root.addEventListener('click', function (e) {
		var el = e.target.closest('button');
		if (!el) {
			return;
		}
		if (el.hasAttribute('data-lang')) {
			lang = el.getAttribute('data-lang');
		} else if (el.classList.contains('answer')) {
			picks[step] = QUESTIONS[step].a[+el.getAttribute('data-i')][0];
			step++;
		} else if (el.classList.contains('quiz-back')) {
			step--;
			picks.length = step;
		} else if (el.id === 'quiz-again') {
			step = 0;
			picks = [];
		} else {
			return;
		}
		render();
		if (!el.hasAttribute('data-lang')) {
			root.scrollIntoView({ behavior: 'smooth', block: 'start' });
		}
	});

	render();
